"""Account tables: teams, users, login sessions.

teams                 Teams. One team per installation for now; the first team reuses the
personal-mode team id, so existing data is preserved.
users                 Users: user name, password hash, role, granted permissions, active flag.
auth_sessions         Login sessions: one row per login with the token hash and expiry. Logout
marks the session revoked.
password_reset_codes  One-time reset codes: generated by an administrator when a user forgets the
password; the user sets a new password with it.
profiles              Profiles: avatar, and the display name in personal mode (in team mode the
display name is users.display_name)."""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import DateTime, ForeignKey, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from jacara.core.db import Base, JsonColumn, TimestampMixin, new_id


class Team(Base, TimestampMixin):
    __tablename__ = "teams"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=new_id)
    name: Mapped[str] = mapped_column(String(100))


class User(Base, TimestampMixin):
    __tablename__ = "users"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=new_id)
    team_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("teams.id"), index=True)
    username: Mapped[str] = mapped_column(String(64), unique=True)
    """Login name, lowercase."""
    display_name: Mapped[str] = mapped_column(String(100), default="")
    password_hash: Mapped[str] = mapped_column(String(255))
    """Argon2id hash, never the plaintext password."""
    role: Mapped[str] = mapped_column(String(16))
    """admin or member."""
    permissions: Mapped[list[Any]] = mapped_column(JsonColumn, default=list, server_default="[]")
    """Permissions granted to this member by an administrator, for example ["document:create",
    "value:review"]."""
    is_active: Mapped[bool] = mapped_column(default=True)
    """Deactivated users cannot log in and their existing sessions are revoked immediately. Users
    are never deleted, because change history still refers to them."""

    team: Mapped[Team] = relationship()


class AuthSession(Base, TimestampMixin):
    __tablename__ = "auth_sessions"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=new_id)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"), index=True)
    token_hash: Mapped[str] = mapped_column(String(64), unique=True)
    """SHA-256 of the token. The plaintext token is never stored."""
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    """Logout time; empty while the session is active."""

    user: Mapped[User] = relationship()


class PasswordResetCode(Base, TimestampMixin):
    """One-time reset code for a forgotten password. Generated by an administrator and passed to the
    user, who sets a new password with it.

        Only the hash is stored, as with login tokens; expires after 15 minutes and is
    invalidated after one use."""

    __tablename__ = "password_reset_codes"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=new_id)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"), index=True)
    """Recipient."""
    code_hash: Mapped[str] = mapped_column(String(64), unique=True)
    """SHA-256 of the reset code. The plaintext is never stored."""
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    used_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    """Time the code was used or revoked; empty while it is still valid."""
    created_by: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id"))
    """Administrator who generated it."""


class Profile(Base, TimestampMixin):
    """User profile, one row per user (absent for users who never set an avatar or display name).

        user_id has no foreign key to users: personal mode has no user accounts and uses the
    fixed PERSONAL_OWNER.user_id. The avatar image is stored in object storage at
    avatars/<user_id>.png; this table records only the time of the last change (also used as a
    version)."""

    __tablename__ = "profiles"

    user_id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    team_id: Mapped[uuid.UUID] = mapped_column(index=True)
    display_name: Mapped[str | None] = mapped_column(String(100))
    """Display name in personal mode. Not used in team mode, where it is stored in
    users.display_name (also editable by administrators)."""
    avatar_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    """Time of the last avatar change; empty when there is no avatar."""
