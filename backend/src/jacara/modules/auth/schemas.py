"""Public schemas for authentication and user management. Passwords are write-only: no response
contains a password or password hash."""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from jacara.core.security import MIN_PASSWORD_LENGTH

RoleName = Literal["admin", "member"]
"""admin: administrator; member: member."""

Permission = Literal[
    "document:create",
    "document:process",
    "document:delete",
    "value:review",
    "document:review",
    "template:manage",
]
"""Permissions grantable to members; matches GRANTABLE in core/permissions.py."""


class LoginIn(BaseModel):
    username: str = Field(min_length=1, max_length=64)
    password: str = Field(min_length=1, max_length=256)


class UserOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    username: str
    display_name: str
    role: str
    permissions: list[str]
    """Permissions granted to this member by an administrator."""
    is_active: bool
    created_at: datetime


class LoginOut(BaseModel):
    token: str
    """Send with every subsequent request: Authorization: Bearer <token>"""
    expires_at: datetime
    user: UserOut


class UserCreate(BaseModel):
    username: str = Field(min_length=2, max_length=64, pattern=r"^[A-Za-z0-9_.-]+$")
    """Letters, digits and _ . - only; case-insensitive."""
    password: str = Field(min_length=MIN_PASSWORD_LENGTH, max_length=256)
    display_name: str = Field(default="", max_length=100)
    role: RoleName = "member"
    permissions: list[Permission] = []
    """Permissions to grant (members only), for example ["document:create", "value:review"]."""


class UserUpdate(BaseModel):
    """Only the given fields change."""

    role: RoleName | None = None
    permissions: list[Permission] | None = None
    """New permission list (replaces the existing list; does not append)."""
    is_active: bool | None = None
    display_name: str | None = Field(default=None, max_length=100)


class PasswordChange(BaseModel):
    """Change one's own password; the current password proves identity."""

    old_password: str = Field(min_length=1, max_length=256)
    new_password: str = Field(min_length=MIN_PASSWORD_LENGTH, max_length=256)


class ResetCodeOut(BaseModel):
    """One-time reset code generated by an administrator. Shown only once here; the database stores
    only its hash."""

    username: str
    code: str
    """For example K7QM-3XWD. Pass it on in person or by phone; do not post it in group chats."""
    expires_at: datetime


class CodeReset(BaseModel):
    """Forgotten password: user name + reset code from an administrator + new password."""

    username: str = Field(min_length=1, max_length=64)
    code: str = Field(min_length=1, max_length=32)
    password: str = Field(min_length=MIN_PASSWORD_LENGTH, max_length=256)


class MeOut(BaseModel):
    """Current user. The frontend uses mode to decide whether to show the login page."""

    mode: Literal["personal", "team"]
    role: str
    permissions: list[str]
    """All operations currently permitted (including those every member has). The frontend uses this
    to decide which buttons to show."""
    user: UserOut | None
    """null in personal mode, which has no user accounts."""
    shown_name: str = ""
    """Name shown in the top-right corner: the display name, otherwise the user name; in personal
    mode without a display name, "Local user"."""
    avatar_at: datetime | None = None
    """Time of the last avatar change (also the avatar version); null when there is no avatar."""


class PermissionOut(BaseModel):
    name: str
    label: str


class ProfileOut(BaseModel):
    """Content of the profile page."""

    mode: Literal["personal", "team"]
    username: str | None
    """Login name. Absent in personal mode."""
    display_name: str
    """Display name (may be empty)."""
    shown_name: str
    """Effective name: display name → user name → "Local user"."""
    role: str
    team: str
    """Team name. Empty in personal mode."""
    permissions: list[str]
    """Granted permissions among the grantable ones, as display names. All of them for
    administrators."""
    avatar_at: datetime | None
    member_since: datetime | None
    """Account creation time. Absent in personal mode."""


class ProfileUpdate(BaseModel):
    display_name: str = Field(max_length=100)
    """New display name. An empty string removes it and the user name is shown."""
