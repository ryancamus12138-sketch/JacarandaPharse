PROPS_TIMEOUT_S = 2

LICENSE_FILES = {"license": "LICENSE", "notice": "NOTICE", "third_party": "THIRD_PARTY_LICENSES"}
"""Files shipped with the program (resource_dir): this program's license, its attribution and the
licenses of the third-party software it ships (generated by the build)."""


def license_file(which: str) -> Path:
    from jacara.core.config import resource_dir

    return resource_dir() / LICENSE_FILES[which]


class SystemService:
    def __init__(self, session: Session, owner: Owner, settings: Settings) -> None:
        self.session = session
        self.owner = owner
        self.settings = settings

    def info(self) -> SystemInfo:
        require(self.owner, "document:read")
        found = self._info()
        if "system:manage" in allowed(self.owner):
            return found
        # Non-administrators see only version, reachability and data volume; addresses, file names,
        # paths and remedies are withheld.
        found.model.server = ""
        found.model.file = None
        found.model.vision_file = None
        found.watch_dir = None
        found.desktop = None
        found.services = [
            ServiceCheck(
                name=s.name, ok=s.ok, detail=tr("正常") if s.ok else tr("无法连接，请联系管理员")
            )
            for s in found.services
        ]
        return found

    def _info(self) -> SystemInfo:
        return SystemInfo(
            version=__version__,
            mode=self.settings.jacara_mode,
            model=self._model(),
            ocr=_ocr(),
            structure=StructureInfo(
                layout=tr("pp_layout_cdla（rapid-layout 内置）")
                if self.settings.jacara_layout
                else None,
                table=table.name if (table := self.settings.table_model()) else None,
            ),
            watch_dir=str(self.settings.jacara_watch_dir)
            if self.settings.jacara_watch_dir
            else None,
            templates=[
                TemplateInfo(name=t.name, title=t.title, version=t.version)
                for t in (load_template(n) for n in template_names())
            ],
            data=self._data(self.owner.team_id),
            services=[
                ServiceCheck(name=c.name, ok=c.ok, detail=c.detail, hint=c.hint)
                for c in run_checks(self.settings)
            ],
            notice=_read(license_file("notice")),
            third_party=license_file("third_party").is_file(),
            desktop=_desktop() if self.settings.jacara_desktop else None,
        )

    def license_text(self, which: str) -> LicenseText:
        """The text of LICENSE, NOTICE or THIRD_PARTY_LICENSES shipped with the program."""
        require(self.owner, "document:read")
        path = license_file(which)
        if not path.is_file():
            raise FileNotFoundError(path.name)
        return LicenseText(text=_read(path))

    def diagnostics(self) -> Diagnostics:
        """Text for a problem report, as Obsidian's "Show debug info" offers to copy: versions,
        system, models, background processes and service checks. Nothing from documents; paths
        under the home folder are written with ~."""
        require(self.owner, "system:manage")
        from jacara.ops.diagnostics import report

        return Diagnostics(text=report(self._info(), self.settings))

    def _model(self) -> ModelInfo:
        found = self.settings.find_model()
        props = model_props(self.settings.model_server)
        path = props.get("model_path")
        settings = props.get("default_generation_settings") or {}
        context = props.get("n_ctx") or settings.get("n_ctx")
        return ModelInfo(
            server=self.settings.model_server,
            file=found.name if found else None,
            loaded=str(path).replace("\\", "/").rsplit("/", 1)[-1] if path else None,
            context=int(context) if context else None,
            vision_file=mmproj.name if (mmproj := self.settings.find_mmproj()) else None,
            sees_images=bool(
                isinstance(modalities := props.get("modalities"), dict) and modalities.get("vision")
            ),
            vision_mode=self.settings.jacara_vision,
        )

    def _data(self, team: uuid.UUID) -> DataInfo:
        def scalar(query: Any) -> int:
            return int(self.session.scalar(query) or 0)

        exports, export_bytes = ExportRepository(self.session).total_bytes(team)
        return DataInfo(
            documents=scalar(select(func.count()).where(Document.team_id == team)),
            pages=scalar(select(func.sum(Document.page_count)).where(Document.team_id == team)),
            fields=scalar(
                select(func.count(ExtractedValue.id))
                .join(Extraction, ExtractedValue.extraction_id == Extraction.id)
                .where(Extraction.team_id == team)
            ),
            revisions=scalar(select(func.count()).where(ValueRevision.team_id == team)),
            document_bytes=scalar(
                select(func.sum(Document.size_bytes)).where(Document.team_id == team)
            ),
            exports=exports,
            export_bytes=export_bytes,
        )


def vision_info(settings: Settings) -> VisionInfo:
    """Whether the model can process images; the review page uses it to decide whether to offer "ask
    the model about this region". Queries the model server once and is fast."""
    props = model_props(settings.model_server)
    modalities = props.get("modalities")
    mmproj = settings.find_mmproj()
    return VisionInfo(
        sees_images=bool(isinstance(modalities, dict) and modalities.get("vision")),
        mode=settings.jacara_vision,
        file=mmproj.name if mmproj else None,
    )


def model_props(server: str) -> dict[str, Any]:
    """Ask the model server (llama-server /props) which model is loaded and its context length.
    Empty if unreachable."""
    from jacara.core.config import model_api_key

    key = model_api_key()
    headers = {"Authorization": f"Bearer {key}"} if key else {}
    try:
        response = httpx.get(f"{server}/props", headers=headers, timeout=PROPS_TIMEOUT_S)
        data = response.json() if response.status_code == 200 else {}
    except (httpx.HTTPError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def _ocr() -> OcrInfo:
    engine = OcrConfig().engine
    try:
        return OcrInfo(engine=engine, version=version(engine))
    except PackageNotFoundError:
        return OcrInfo(engine=engine, version=None)


def _read(path: Path) -> str:
    try:
        return path.read_text("utf-8").strip()
    except OSError:
        return ""


def _desktop() -> DesktopStatus:
    from jacara.core.config import data_home
    from jacara.desktop import SERVICES, log_dir

    processes = SERVICES.status() if SERVICES is not None else []
    return DesktopStatus(
        data_dir=str(data_home()),
        log_dir=str(log_dir()),
        processes=[ProcessStatus.model_validate(p) for p in processes],
    )
